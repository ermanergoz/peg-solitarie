package com.app.pegsolitaire

import android.Manifest
import android.content.pm.PackageManager
import com.google.common.truth.Truth.assertThat
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config

/**
 * Gates the **merged** manifest surface (PLAT-07): what the manifest merger hands the
 * packager after every library AAR has had its say, which is not what
 * `app/src/main/AndroidManifest.xml` says on its own.
 *
 * **This test is meaningful only because plan 06-09 put `play-services-games-v2` on the
 * dependency graph (D-14).** Before that, [playGamesInitProviderIsNotInTheMergedManifest]
 * passed vacuously — there was no `PlayGamesInitProvider` anywhere in the build, so
 * "it is absent" was true no matter what the app manifest said, and the `tools:node="remove"`
 * it claims to verify could have been deleted without turning this red. A test that cannot
 * fail is not a gate. It can fail now: the provider was confirmed present in the merged
 * release manifest with the dependency added and the removal directive not yet written.
 *
 * Robolectric is the runner because the assertions go through a real [PackageManager]
 * reading a real merged manifest, which is the artifact under test — parsing the XML by
 * hand would test this test's XPath rather than what Android will actually see.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [ROBOLECTRIC_SDK])
class ManifestSurfaceTest {
    private val context = RuntimeEnvironment.getApplication()

    @Test
    fun playGamesInitProviderIsNotInTheMergedManifest() {
        val authority = "${context.packageName}$PLAY_GAMES_INIT_PROVIDER_AUTHORITY_SUFFIX"

        assertThat(context.packageManager.resolveContentProvider(authority, 0)).isNull()
    }

    @Test
    fun theAppDeclaresInternet() {
        assertThat(requestedPermissions()).contains(Manifest.permission.INTERNET)
    }

    @Test
    fun theMergedPermissionSetIsExactlyWhatWeHaveAgreedTo() {
        assertThat(requestedPermissions()).isEqualTo(EXPECTED_PERMISSIONS)
    }

    private fun requestedPermissions(): Set<String> =
        context.packageManager
            .getPackageInfo(context.packageName, PackageManager.GET_PERMISSIONS)
            .requestedPermissions
            .orEmpty()
            .toSet()
}

/** Robolectric has no android-all jar for Android 16 (SDK 36) yet; emulate SDK 34. */
private const val ROBOLECTRIC_SDK = 34

/**
 * The authority `play-services-games-v2` declares for its auto-init provider, as
 * `${applicationId}.playgamesinitprovider`. Read out of the AAR manifest, 2026-08-27.
 */
private const val PLAY_GAMES_INIT_PROVIDER_AUTHORITY_SUFFIX = ".playgamesinitprovider"

/**
 * Every permission the merged manifest may request — asserted by **set equality**, not
 * `contains`.
 *
 * The equality is the entire point and it is deliberately the annoying choice. Permissions
 * arrive here through manifest merge, from AARs, without anyone editing a file in this
 * repository: a routine SDK version bump can add one and the only visible consequence is a
 * changed Play Store listing and a changed Data-safety answer. `contains` would never
 * notice. Equality turns that into a build failure, and a human then decides whether the
 * new permission is acceptable and updates this set on purpose. **Adding an entry here is
 * a decision, not a chore** — if you are here because the build went red, find out which
 * dependency added the permission before you paste it in.
 *
 * Provenance of the current entries, none of which this app asked for except the first:
 * - `INTERNET` — declared by us (D-10). Also merged in by the ads SDK, so declaring it
 *   changes nothing about the merged output; that is exactly why D-10 wanted it explicit,
 *   so the store permission diff is a deliberate commit rather than a merge side effect.
 * - `ACCESS_NETWORK_STATE`, `READ_BASIC_PHONE_STATE`, `com.google.android.gms.permission.AD_ID`
 *   — `ads-mobile-sdk`. `AD_ID` is the privacy-relevant one and drives a Data-safety answer.
 * - `WAKE_LOCK`, `FOREGROUND_SERVICE` — `androidx.work`, pulled in transitively by the ads
 *   SDK rather than by any choice made here.
 * - `${applicationId}.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION` — generated by AGP for
 *   `androidx.core`'s runtime receiver registration. Interpolated because D-20 changed
 *   `applicationId` to `com.erman.pegsolitarie` while the namespace stayed
 *   `com.app.pegsolitaire`; hard-coding it would pin the wrong one.
 * - `REORDER_TASKS` — `androidx.compose.ui:ui-test-manifest`, a `debugImplementation`
 *   dependency. It reaches the unit-test manifest this test reads but never a release
 *   build, so its presence here is an artifact of where the assertion runs.
 */
private val EXPECTED_PERMISSIONS: Set<String> =
    setOf(
        Manifest.permission.INTERNET,
        Manifest.permission.ACCESS_NETWORK_STATE,
        "android.permission.READ_BASIC_PHONE_STATE",
        "com.google.android.gms.permission.AD_ID",
        Manifest.permission.WAKE_LOCK,
        Manifest.permission.FOREGROUND_SERVICE,
        Manifest.permission.REORDER_TASKS,
        "$APPLICATION_ID.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION",
    )

/**
 * The `applicationId` (D-20), which is **not** the namespace and therefore not
 * `BuildConfig.APPLICATION_ID`'s package. Named once here so the two AGP-generated
 * permission names above cannot drift from it silently.
 */
private const val APPLICATION_ID = "com.erman.pegsolitarie"
