package com.app.pegsolitaire.data.db

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.Query
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_ELAPSED_MS
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_HINTS_USED
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_LAST_PEG_ON_TARGET
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_LEVEL_ID
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_MODE
import com.app.pegsolitaire.data.ProgressPersistenceKeys.COLUMN_UNDOS_USED
import com.app.pegsolitaire.data.ProgressPersistenceKeys.TABLE_PLAY_SESSION

/**
 * Appends solved plays to the telemetry history (PGSA-06) and answers the four skill
 * predicates derived from it.
 *
 * The read surface is deliberately narrow: exactly one projection query, [flags], which
 * answers all four of the D-01/D-04 skill one-shots in a single round trip. Mirroring
 * [LevelResultDao]'s "this DAO stays a dumb store" note, no merge or rule logic lives
 * here — `AchievementRules` consumes the folded aggregate, never these rows.
 *
 * [Insert] rather than `@Upsert` is the correct verb — the primary key is autogenerated
 * and rows are append-only, so there is never an existing row to replace. Room compiles
 * and binds every statement, so no caller-supplied value can alter one (T-12-05/T-12-32).
 */
@Dao
interface PlaySessionDao {
    /** Appends one solved play; the autogenerated key is assigned by SQLite. */
    @Insert
    suspend fun insert(entity: PlaySessionEntity)

    /**
     * The four telemetry-derived skill predicates in ONE round trip.
     *
     * A `FROM`-less `SELECT` of four `EXISTS` sub-selects, so it always returns exactly
     * one row and the return type is non-null.
     *
     * Two of the predicates carry **no mode filter on purpose** (D-01): a hint-free or
     * undo-free solve in EITHER mode earns its achievement, and adding a mode filter here
     * would be a silent scope reduction. The center-finish predicate is the opposite case:
     * `GameViewModel` records `lastPegOnTarget` for every board, and THIS QUERY is the only
     * place in the codebase where the D-01 "English-33 finishing on `(3, 3)` and nowhere
     * else" narrowing exists. The comparison is against `1` rather than `true` because Room
     * stores a Kotlin `Boolean` as `INTEGER NOT NULL`.
     *
     * The speed bound is a strict `<` — "under 60 seconds", so exactly the limit does not
     * qualify (D-04).
     *
     * @param classicMode bound `ProgressPersistenceKeys.MODE_CLASSIC`.
     * @param english33Id bound `ClassicLevelIds.ENGLISH33`.
     * @param speedLimitMs bound `AchievementThresholds.SPEED_SOLVE_MAX_ELAPSED_MS`, so the
     *   60 seconds exists in exactly one place in the codebase.
     */
    @Query(
        """
        SELECT
          EXISTS(SELECT 1 FROM $TABLE_PLAY_SESSION
                   WHERE $COLUMN_HINTS_USED = 0) AS anyHintFreeSolve,
          EXISTS(SELECT 1 FROM $TABLE_PLAY_SESSION
                   WHERE $COLUMN_UNDOS_USED = 0) AS anyUndoFreeSolve,
          EXISTS(SELECT 1 FROM $TABLE_PLAY_SESSION
                   WHERE $COLUMN_MODE = :classicMode AND $COLUMN_LEVEL_ID = :english33Id
                     AND $COLUMN_LAST_PEG_ON_TARGET = 1) AS anyCenterFinish,
          EXISTS(SELECT 1 FROM $TABLE_PLAY_SESSION
                   WHERE $COLUMN_ELAPSED_MS < :speedLimitMs) AS anySpeedSolve
        """,
    )
    suspend fun flags(
        classicMode: String,
        english33Id: String,
        speedLimitMs: Long,
    ): PlaySessionFlags
}
